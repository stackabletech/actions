//! Merges the components that syft reports more than once and completes the dependency graph.

use std::collections::{BTreeMap, BTreeSet};

use cyclonedx_bom::{
    models::{
        component::{Classification, Component},
        dependency::{Dependencies, Dependency},
    },
    prelude::{Bom, NormalizedString},
};

pub const FOUND_BY_PROPERTY: &str = "syft:package:foundBy";
pub const FIRST_LOCATION_PROPERTY: &str = "syft:location:0:path";
pub const VIRTUAL_PATH_PROPERTY: &str = "syft:metadata:virtualPath";

const JAVA_ARCHIVE_CATALOGER: &str = "java-archive-cataloger";
const SBOM_CATALOGER: &str = "sbom-cataloger";

/// The parts of a component that are needed to decide how to merge it.
#[derive(Debug)]
struct CatalogedComponent {
    bom_ref: String,
    purl: Option<String>,
    virtual_path: Option<String>,
}

/// Components grouped by the syft cataloger that found them and the path they were found at.
type GroupedComponents = BTreeMap<String, BTreeMap<String, Vec<CatalogedComponent>>>;

/// Merges duplicate components and completes the dependency graph, in place.
///
/// 1. Components found inside a jar by syft's java-archive-cataloger become dependencies of that
///    jar.
/// 2. Components with the same purl (ignoring qualifiers) are merged into one. A component that
///    comes from an SBOM embedded in the image (sbom-cataloger) wins over the ones syft found
///    itself, because the embedded SBOMs are generated by the build and are more accurate.
///    Dependencies of a removed component are moved to the component it was merged into.
/// 3. Dependencies that point to no component are pointed to the component with the same purl,
///    or removed if there is none.
/// 4. Every component that no other component depends on becomes a dependency of the root
///    component (the image), so every component is reachable from the root. Components that
///    only depend on each other count as a whole: all of them become dependencies of the root.
/// 5. The operating system component is renamed from `rhel` to `redhat`, because Trivy does not
///    recognise `rhel`.
pub fn merge_components(bom: &mut Bom, root_bom_ref: &str) {
    let grouped_components = group_components(bom);

    add_jar_dependencies(bom, &grouped_components);
    merge_duplicate_components(bom, &grouped_components);
    resolve_dangling_dependencies(bom, root_bom_ref);
    deduplicate_dependencies(bom);
    attach_top_level_components(bom, root_bom_ref);
    rename_operating_system(bom);
}

/// Returns the value of the first property with the given name.
pub fn property<'a>(component: &'a Component, name: &str) -> Option<&'a str> {
    component
        .properties
        .as_ref()?
        .0
        .iter()
        .find(|property| property.name == name)
        .map(|property| property.value.as_ref())
}

fn components(bom: &Bom) -> &[Component] {
    bom.components
        .as_ref()
        .map(|components| components.0.as_slice())
        .unwrap_or_default()
}

/// Strips the qualifiers (everything after `?`) from a purl.
fn purl_without_qualifiers(purl: &str) -> &str {
    purl.split_once('?')
        .map_or(purl, |(purl, _qualifiers)| purl)
}

fn group_components(bom: &Bom) -> GroupedComponents {
    let mut grouped_components = GroupedComponents::new();

    for component in components(bom) {
        let (Some(bom_ref), Some(found_by), Some(path)) = (
            component.bom_ref.as_ref(),
            property(component, FOUND_BY_PROPERTY),
            property(component, FIRST_LOCATION_PROPERTY),
        ) else {
            continue;
        };

        grouped_components
            .entry(found_by.to_owned())
            .or_default()
            .entry(path.to_owned())
            .or_default()
            .push(CatalogedComponent {
                bom_ref: bom_ref.clone(),
                purl: component.purl.as_ref().map(ToString::to_string),
                virtual_path: property(component, VIRTUAL_PATH_PROPERTY).map(ToOwned::to_owned),
            });
    }

    grouped_components
}

fn add_jar_dependencies(bom: &mut Bom, grouped_components: &GroupedComponents) {
    let Some(jars) = grouped_components.get(JAVA_ARCHIVE_CATALOGER) else {
        return;
    };

    let dependencies = &mut bom
        .dependencies
        .get_or_insert_with(|| Dependencies(vec![]))
        .0;

    for (jar_path, jar_components) in jars {
        let (parents, children): (Vec<_>, Vec<_>) = jar_components
            .iter()
            .partition(|component| component.virtual_path.as_deref() == Some(jar_path.as_str()));

        if let Some(parent) = parents.first() {
            if !children.is_empty() {
                dependencies.push(Dependency {
                    dependency_ref: parent.bom_ref.clone(),
                    dependencies: children.iter().map(|child| child.bom_ref.clone()).collect(),
                    provides: vec![],
                });
            }
        }
    }
}

fn merge_duplicate_components(bom: &mut Bom, grouped_components: &GroupedComponents) {
    // The component that is kept for a purl. Components from embedded SBOMs are registered first,
    // so they win over components syft found itself.
    let mut kept_bom_refs = BTreeMap::<String, String>::new();
    for component in grouped_components
        .get(SBOM_CATALOGER)
        .into_iter()
        .flat_map(BTreeMap::values)
        .flatten()
    {
        if let Some(purl) = &component.purl {
            kept_bom_refs
                .entry(purl_without_qualifiers(purl).to_owned())
                .or_insert_with(|| component.bom_ref.clone());
        }
    }

    // Maps the bom-ref of every removed component to the bom-ref it was merged into.
    let mut replaced_bom_refs = BTreeMap::<String, String>::new();
    let Some(components) = bom.components.as_mut() else {
        return;
    };
    components.0.retain(|component| {
        let (Some(purl), Some(bom_ref)) = (&component.purl, &component.bom_ref) else {
            return true;
        };

        let kept_bom_ref = kept_bom_refs
            .entry(purl_without_qualifiers(purl.as_ref()).to_owned())
            .or_insert_with(|| bom_ref.clone());

        if kept_bom_ref == bom_ref {
            true
        } else {
            replaced_bom_refs.insert(bom_ref.clone(), kept_bom_ref.clone());
            false
        }
    });

    if let Some(dependencies) = bom.dependencies.as_mut() {
        let replace = |bom_ref: &mut String| {
            if let Some(kept_bom_ref) = replaced_bom_refs.get(bom_ref) {
                bom_ref.clone_from(kept_bom_ref);
            }
        };

        for dependency in &mut dependencies.0 {
            replace(&mut dependency.dependency_ref);
            dependency.dependencies.iter_mut().for_each(replace);
        }
    }
}

/// Repairs the dependencies that point to no component.
///
/// syft copies the dependencies of an embedded SBOM, but it does not always keep the bom-ref of
/// the component they point to. A Rust crate that depends on another crate of the same workspace
/// by path is referenced with qualifiers the component itself does not have. The bom-refs of syft
/// are purls, so such a reference is pointed to the component with the same purl. A reference
/// that still points to nothing is removed, since it is not valid CycloneDX.
fn resolve_dangling_dependencies(bom: &mut Bom, root_bom_ref: &str) {
    let mut bom_refs = BTreeSet::from([root_bom_ref]);
    let mut bom_refs_by_purl = BTreeMap::<&str, &str>::new();
    for component in components(bom) {
        let Some(bom_ref) = component.bom_ref.as_deref() else {
            continue;
        };
        bom_refs.insert(bom_ref);
        if let Some(purl) = &component.purl {
            bom_refs_by_purl
                .entry(purl_without_qualifiers(purl.as_ref()))
                .or_insert(bom_ref);
        }
    }

    let resolve = |bom_ref: &String| -> Option<String> {
        if bom_refs.contains(bom_ref.as_str()) {
            Some(bom_ref.clone())
        } else {
            bom_refs_by_purl
                .get(purl_without_qualifiers(bom_ref))
                .map(|bom_ref| (*bom_ref).to_owned())
        }
    };

    let resolved: Vec<Dependency> = bom
        .dependencies
        .iter()
        .flat_map(|dependencies| &dependencies.0)
        .filter_map(|dependency| {
            Some(Dependency {
                dependency_ref: resolve(&dependency.dependency_ref)?,
                dependencies: dependency.dependencies.iter().filter_map(resolve).collect(),
                provides: dependency.provides.clone(),
            })
        })
        .collect();

    if let Some(dependencies) = bom.dependencies.as_mut() {
        dependencies.0 = resolved;
    }
}

/// Combines dependency entries with the same `ref` and removes duplicate and self references.
///
/// The result is sorted, so the output is the same for the same input.
fn deduplicate_dependencies(bom: &mut Bom) {
    let Some(dependencies) = bom.dependencies.as_mut() else {
        return;
    };

    let mut combined = BTreeMap::<String, BTreeSet<String>>::new();
    for dependency in dependencies.0.drain(..) {
        let entry = combined.entry(dependency.dependency_ref).or_default();
        entry.extend(dependency.dependencies);
    }

    dependencies.0 = combined
        .into_iter()
        .map(|(dependency_ref, mut depends_on)| {
            depends_on.remove(&dependency_ref);
            Dependency {
                dependency_ref,
                dependencies: depends_on.into_iter().collect(),
                provides: vec![],
            }
        })
        .collect();
}

/// Makes every component reachable from the root component.
///
/// A component that no other component depends on becomes a dependency of the root. That alone
/// is not enough: packages that depend on each other (`apache-airflow` and its providers, or
/// `glibc` and `glibc-common`) all have a parent, but nothing leads to them from the root. Such a
/// cycle is treated like a single component, and if nothing outside of it depends on it, all of
/// its members become dependencies of the root.
fn attach_top_level_components(bom: &mut Bom, root_bom_ref: &str) {
    let dependencies = bom.dependencies.get_or_insert_with(|| Dependencies(vec![]));

    let bom_refs: Vec<&str> = bom
        .components
        .as_ref()
        .map(|components| components.0.as_slice())
        .unwrap_or_default()
        .iter()
        .filter_map(|component| component.bom_ref.as_deref())
        .filter(|bom_ref| *bom_ref != root_bom_ref)
        .collect();
    let indices: BTreeMap<&str, usize> = bom_refs
        .iter()
        .enumerate()
        .map(|(index, bom_ref)| (*bom_ref, index))
        .collect();

    let mut children = vec![Vec::new(); bom_refs.len()];
    let mut is_root_dependency = vec![false; bom_refs.len()];
    for dependency in &dependencies.0 {
        let parent = indices.get(dependency.dependency_ref.as_str());
        for child in &dependency.dependencies {
            let Some(child) = indices.get(child.as_str()) else {
                continue;
            };
            if dependency.dependency_ref == root_bom_ref {
                is_root_dependency[*child] = true;
            } else if let Some(parent) = parent {
                children[*parent].push(*child);
            }
        }
    }

    // A cycle has a parent if a component outside of it (or the root) depends on a member.
    let cycles = strongly_connected_components(&children);
    let mut has_parent = vec![false; bom_refs.len()];
    for (parent, children) in children.iter().enumerate() {
        for child in children {
            if cycles[parent] != cycles[*child] {
                has_parent[cycles[*child]] = true;
            }
        }
    }
    for (component, is_root_dependency) in is_root_dependency.iter().enumerate() {
        if *is_root_dependency {
            has_parent[cycles[component]] = true;
        }
    }

    let top_level_components: Vec<String> = bom_refs
        .iter()
        .enumerate()
        .filter(|(component, _)| !has_parent[cycles[*component]])
        .map(|(_, bom_ref)| (*bom_ref).to_owned())
        .collect();

    match dependencies
        .0
        .iter_mut()
        .find(|dependency| dependency.dependency_ref == root_bom_ref)
    {
        Some(root_dependency) => root_dependency.dependencies.extend(top_level_components),
        None => dependencies.0.push(Dependency {
            dependency_ref: root_bom_ref.to_owned(),
            dependencies: top_level_components,
            provides: vec![],
        }),
    }
}

/// Assigns every node of a graph to its strongly connected component: two nodes get the same
/// number if and only if each of them is reachable from the other. A node that is part of no
/// cycle is a component of its own.
///
/// `children` holds the nodes each node points to. This is Kosaraju's algorithm, without
/// recursion because dependency chains can be thousands of components long.
fn strongly_connected_components(children: &[Vec<usize>]) -> Vec<usize> {
    let node_count = children.len();

    // Depth-first search that records the nodes in the order it is done with them.
    let mut finished = Vec::with_capacity(node_count);
    let mut visited = vec![false; node_count];
    for start in 0..node_count {
        if visited[start] {
            continue;
        }
        visited[start] = true;

        // The nodes on the current path, each with the position of its next unvisited child.
        let mut path = vec![(start, 0)];
        while let Some((node, next_child)) = path.last_mut() {
            if let Some(child) = children[*node].get(*next_child) {
                *next_child += 1;
                if !visited[*child] {
                    visited[*child] = true;
                    path.push((*child, 0));
                }
            } else {
                finished.push(*node);
                path.pop();
            }
        }
    }

    let mut parents = vec![Vec::new(); node_count];
    for (node, children) in children.iter().enumerate() {
        for child in children {
            parents[*child].push(node);
        }
    }

    // Following the edges backwards from the node that was finished last only reaches the nodes
    // of its own component, and so on for every node that is still unassigned after that.
    let mut components = vec![None; node_count];
    let mut component_count = 0;
    for start in finished.into_iter().rev() {
        if components[start].is_some() {
            continue;
        }
        components[start] = Some(component_count);

        let mut pending = vec![start];
        while let Some(node) = pending.pop() {
            for parent in &parents[node] {
                if components[*parent].is_none() {
                    components[*parent] = Some(component_count);
                    pending.push(*parent);
                }
            }
        }
        component_count += 1;
    }

    // Every node is in `finished`, so every node was assigned above.
    components.into_iter().flatten().collect()
}

fn rename_operating_system(bom: &mut Bom) {
    let Some(components) = bom.components.as_mut() else {
        return;
    };

    for component in &mut components.0 {
        if component.component_type == Classification::OperatingSystem
            && component.name.to_string() == "rhel"
        {
            component.name = NormalizedString::new("redhat");
        }
    }
}

#[cfg(test)]
mod tests {
    use rstest::rstest;
    use serde_json::json;

    use super::*;

    const ROOT: &str = "root";

    /// Builds an SBOM with the given components (bom-ref and purl) and dependencies (from, to),
    /// and merges it. Returns the dependencies of the result.
    fn merged_dependencies(
        components: &[(&str, &str)],
        dependencies: &[(&str, &str)],
    ) -> BTreeMap<String, Vec<String>> {
        let sbom = json!({
            "bomFormat": "CycloneDX",
            "specVersion": "1.5",
            "version": 1,
            "metadata": {
                "component": { "type": "container", "bom-ref": ROOT, "name": "image" }
            },
            "components": components
                .iter()
                .map(|(bom_ref, purl)| json!({
                    "type": "library",
                    "bom-ref": bom_ref,
                    "name": bom_ref,
                    "purl": purl,
                }))
                .collect::<Vec<_>>(),
            "dependencies": dependencies
                .iter()
                .map(|(from, to)| json!({ "ref": from, "dependsOn": [to] }))
                .collect::<Vec<_>>(),
        });
        let mut bom = Bom::parse_from_json(sbom.to_string().as_bytes())
            .expect("the test SBOM should be a valid CycloneDX SBOM");

        merge_components(&mut bom, ROOT);

        bom.dependencies
            .expect("the merged SBOM should have dependencies")
            .0
            .into_iter()
            .map(|dependency| (dependency.dependency_ref, dependency.dependencies))
            .collect()
    }

    #[rstest]
    #[case::without_dependencies(&[], &["a", "b", "c", "d"])]
    #[case::chain(&[("a", "b"), ("b", "c"), ("c", "d")], &["a"])]
    #[case::two_trees(&[("a", "b"), ("c", "d")], &["a", "c"])]
    // Nothing leads into the cycle of a and b, so both are top level.
    #[case::cycle(&[("a", "b"), ("b", "a"), ("b", "c")], &["a", "b", "d"])]
    #[case::whole_graph_is_a_cycle(
        &[("a", "b"), ("b", "c"), ("c", "d"), ("d", "a")],
        &["a", "b", "c", "d"]
    )]
    // The cycle of b and c is reachable through a.
    #[case::cycle_with_parent(&[("a", "b"), ("b", "c"), ("c", "b"), ("c", "d")], &["a"])]
    #[case::two_cycles(
        &[("a", "b"), ("b", "a"), ("b", "c"), ("c", "d"), ("d", "c")],
        &["a", "b"]
    )]
    // The root already leads into the cycle of a and b.
    #[case::cycle_below_root(&[(ROOT, "a"), ("a", "b"), ("b", "a")], &["a", "c", "d"])]
    fn attach_top_level_components_to_root(
        #[case] dependencies: &[(&str, &str)],
        #[case] expected_root_dependencies: &[&str],
    ) {
        // The purls do not matter here, they only have to differ.
        let components = [
            ("a", "pkg:a"),
            ("b", "pkg:b"),
            ("c", "pkg:c"),
            ("d", "pkg:d"),
        ];
        let merged = merged_dependencies(&components, dependencies);

        assert_eq!(merged[ROOT], expected_root_dependencies);

        // Whatever the root depends on directly, everything has to be reachable from it.
        let mut reachable = BTreeSet::new();
        let mut pending = vec![ROOT];
        while let Some(bom_ref) = pending.pop() {
            if reachable.insert(bom_ref) {
                pending.extend(
                    merged
                        .get(bom_ref)
                        .into_iter()
                        .flatten()
                        .map(String::as_str),
                );
            }
        }
        assert_eq!(reachable, BTreeSet::from([ROOT, "a", "b", "c", "d"]));
    }

    #[rstest]
    fn resolve_dangling_dependencies_by_purl() {
        const OPERATOR: &str = "pkg:cargo/operator@1.0.0?package-id=1";
        const KEYTAB: &str = "pkg:cargo/keytab@1.0.0?package-id=2";

        // The operator depends on a crate of its workspace by path. syft references that crate
        // with a download_url qualifier that the bom-ref of the component does not have.
        let merged = merged_dependencies(
            &[
                (OPERATOR, "pkg:cargo/operator@1.0.0"),
                (KEYTAB, "pkg:cargo/keytab@1.0.0"),
            ],
            &[
                (
                    OPERATOR,
                    "pkg:cargo/keytab@1.0.0?download_url=file%3A%2F%2F..%2Fkeytab",
                ),
                (OPERATOR, "pkg:cargo/gone@1.0.0"),
                ("pkg:cargo/gone@1.0.0", KEYTAB),
            ],
        );

        assert_eq!(
            merged,
            BTreeMap::from([
                (OPERATOR.to_owned(), vec![KEYTAB.to_owned()]),
                (ROOT.to_owned(), vec![OPERATOR.to_owned()]),
            ])
        );
    }

    #[rstest]
    #[case::no_edges(&[], [false, false, false])]
    #[case::chain(&[(0, 1), (1, 2)], [false, false, false])]
    #[case::cycle(&[(0, 1), (1, 2), (2, 0)], [true, true, true])]
    #[case::cycle_with_tail(&[(0, 1), (1, 0), (1, 2)], [true, true, false])]
    #[case::cycle_with_head(&[(0, 1), (1, 2), (2, 1)], [false, true, true])]
    fn strongly_connected_components_are_cycles(
        #[case] edges: &[(usize, usize)],
        #[case] is_in_cycle: [bool; 3],
    ) {
        let mut children = vec![Vec::new(); 3];
        for (from, to) in edges {
            children[*from].push(*to);
        }

        let components = strongly_connected_components(&children);

        let shares_component = [0, 1, 2].map(|node| {
            components
                .iter()
                .filter(|component| **component == components[node])
                .count()
                > 1
        });
        assert_eq!(shares_component, is_in_cycle);
    }
}
