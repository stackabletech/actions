//! Merges the components that syft reports more than once and completes the dependency graph.

use std::collections::{BTreeMap, BTreeSet, HashSet};

use cyclonedx_bom::{
    models::{
        component::{Classification, Component},
        dependency::{Dependencies, Dependency},
    },
    prelude::{Bom, NormalizedString},
};

pub const FOUND_BY_PROPERTY: &str = "syft:package:foundBy";
pub const FIRST_LOCATION_PROPERTY: &str = "syft:location:0:path";
pub const VIRTUAL_PATH_PROPERTY: &str = "syft:metadata:virtualPath";

const JAVA_ARCHIVE_CATALOGER: &str = "java-archive-cataloger";
const SBOM_CATALOGER: &str = "sbom-cataloger";

/// The parts of a component that are needed to decide how to merge it.
#[derive(Debug)]
struct CatalogedComponent {
    bom_ref: String,
    purl: Option<String>,
    virtual_path: Option<String>,
}

/// Components grouped by the syft cataloger that found them and the path they were found at.
type GroupedComponents = BTreeMap<String, BTreeMap<String, Vec<CatalogedComponent>>>;

/// Merges duplicate components and completes the dependency graph, in place.
///
/// 1. Components found inside a jar by syft's java-archive-cataloger become dependencies of that
///    jar.
/// 2. Components with the same purl (ignoring qualifiers) are merged into one. A component that
///    comes from an SBOM embedded in the image (sbom-cataloger) wins over the ones syft found
///    itself, because the embedded SBOMs are generated by the build and are more accurate.
///    Dependencies of a removed component are moved to the component it was merged into.
/// 3. Every component that is not a dependency of another component becomes a dependency of the
///    root component (the image), so the graph has a single root.
/// 4. The operating system component is renamed from `rhel` to `redhat`, because Trivy does not
///    recognise `rhel`.
pub fn merge_components(bom: &mut Bom, root_bom_ref: &str) {
    let grouped_components = group_components(bom);

    add_jar_dependencies(bom, &grouped_components);
    merge_duplicate_components(bom, &grouped_components);
    deduplicate_dependencies(bom);
    attach_parentless_components(bom, root_bom_ref);
    rename_operating_system(bom);
}

/// Returns the value of the first property with the given name.
pub fn property<'a>(component: &'a Component, name: &str) -> Option<&'a str> {
    component
        .properties
        .as_ref()?
        .0
        .iter()
        .find(|property| property.name == name)
        .map(|property| property.value.as_ref())
}

fn components(bom: &Bom) -> &[Component] {
    bom.components
        .as_ref()
        .map(|components| components.0.as_slice())
        .unwrap_or_default()
}

/// Strips the qualifiers (everything after `?`) from a purl.
fn purl_without_qualifiers(purl: &str) -> &str {
    purl.split_once('?')
        .map_or(purl, |(purl, _qualifiers)| purl)
}

fn group_components(bom: &Bom) -> GroupedComponents {
    let mut grouped_components = GroupedComponents::new();

    for component in components(bom) {
        let (Some(bom_ref), Some(found_by), Some(path)) = (
            component.bom_ref.as_ref(),
            property(component, FOUND_BY_PROPERTY),
            property(component, FIRST_LOCATION_PROPERTY),
        ) else {
            continue;
        };

        grouped_components
            .entry(found_by.to_owned())
            .or_default()
            .entry(path.to_owned())
            .or_default()
            .push(CatalogedComponent {
                bom_ref: bom_ref.clone(),
                purl: component.purl.as_ref().map(ToString::to_string),
                virtual_path: property(component, VIRTUAL_PATH_PROPERTY).map(ToOwned::to_owned),
            });
    }

    grouped_components
}

fn add_jar_dependencies(bom: &mut Bom, grouped_components: &GroupedComponents) {
    let Some(jars) = grouped_components.get(JAVA_ARCHIVE_CATALOGER) else {
        return;
    };

    let dependencies = &mut bom
        .dependencies
        .get_or_insert_with(|| Dependencies(vec![]))
        .0;

    for (jar_path, jar_components) in jars {
        let (parents, children): (Vec<_>, Vec<_>) = jar_components
            .iter()
            .partition(|component| component.virtual_path.as_deref() == Some(jar_path.as_str()));

        if let Some(parent) = parents.first() {
            if !children.is_empty() {
                dependencies.push(Dependency {
                    dependency_ref: parent.bom_ref.clone(),
                    dependencies: children.iter().map(|child| child.bom_ref.clone()).collect(),
                    provides: vec![],
                });
            }
        }
    }
}

fn merge_duplicate_components(bom: &mut Bom, grouped_components: &GroupedComponents) {
    // The component that is kept for a purl. Components from embedded SBOMs are registered first,
    // so they win over components syft found itself.
    let mut kept_bom_refs = BTreeMap::<String, String>::new();
    for component in grouped_components
        .get(SBOM_CATALOGER)
        .into_iter()
        .flat_map(BTreeMap::values)
        .flatten()
    {
        if let Some(purl) = &component.purl {
            kept_bom_refs
                .entry(purl_without_qualifiers(purl).to_owned())
                .or_insert_with(|| component.bom_ref.clone());
        }
    }

    // Maps the bom-ref of every removed component to the bom-ref it was merged into.
    let mut replaced_bom_refs = BTreeMap::<String, String>::new();
    let Some(components) = bom.components.as_mut() else {
        return;
    };
    components.0.retain(|component| {
        let (Some(purl), Some(bom_ref)) = (&component.purl, &component.bom_ref) else {
            return true;
        };

        let kept_bom_ref = kept_bom_refs
            .entry(purl_without_qualifiers(purl.as_ref()).to_owned())
            .or_insert_with(|| bom_ref.clone());

        if kept_bom_ref == bom_ref {
            true
        } else {
            replaced_bom_refs.insert(bom_ref.clone(), kept_bom_ref.clone());
            false
        }
    });

    if let Some(dependencies) = bom.dependencies.as_mut() {
        let replace = |bom_ref: &mut String| {
            if let Some(kept_bom_ref) = replaced_bom_refs.get(bom_ref) {
                bom_ref.clone_from(kept_bom_ref);
            }
        };

        for dependency in &mut dependencies.0 {
            replace(&mut dependency.dependency_ref);
            dependency.dependencies.iter_mut().for_each(replace);
        }
    }
}

/// Combines dependency entries with the same `ref` and removes duplicate and self references.
///
/// The result is sorted, so the output is the same for the same input.
fn deduplicate_dependencies(bom: &mut Bom) {
    let Some(dependencies) = bom.dependencies.as_mut() else {
        return;
    };

    let mut combined = BTreeMap::<String, BTreeSet<String>>::new();
    for dependency in dependencies.0.drain(..) {
        let entry = combined.entry(dependency.dependency_ref).or_default();
        entry.extend(dependency.dependencies);
    }

    dependencies.0 = combined
        .into_iter()
        .map(|(dependency_ref, mut depends_on)| {
            depends_on.remove(&dependency_ref);
            Dependency {
                dependency_ref,
                dependencies: depends_on.into_iter().collect(),
                provides: vec![],
            }
        })
        .collect();
}

fn attach_parentless_components(bom: &mut Bom, root_bom_ref: &str) {
    let dependencies = bom.dependencies.get_or_insert_with(|| Dependencies(vec![]));

    let children: HashSet<&str> = dependencies
        .0
        .iter()
        .flat_map(|dependency| dependency.dependencies.iter().map(String::as_str))
        .collect();

    let parentless_components: Vec<String> = bom
        .components
        .as_ref()
        .map(|components| components.0.as_slice())
        .unwrap_or_default()
        .iter()
        .filter_map(|component| component.bom_ref.as_deref())
        .filter(|bom_ref| !children.contains(bom_ref) && *bom_ref != root_bom_ref)
        .map(ToOwned::to_owned)
        .collect();

    match dependencies
        .0
        .iter_mut()
        .find(|dependency| dependency.dependency_ref == root_bom_ref)
    {
        Some(root_dependency) => {
            for bom_ref in parentless_components {
                if !root_dependency.dependencies.contains(&bom_ref) {
                    root_dependency.dependencies.push(bom_ref);
                }
            }
        }
        None => dependencies.0.push(Dependency {
            dependency_ref: root_bom_ref.to_owned(),
            dependencies: parentless_components,
            provides: vec![],
        }),
    }
}

fn rename_operating_system(bom: &mut Bom) {
    let Some(components) = bom.components.as_mut() else {
        return;
    };

    for component in &mut components.0 {
        if component.component_type == Classification::OperatingSystem
            && component.name.to_string() == "rhel"
        {
            component.name = NormalizedString::new("redhat");
        }
    }
}
